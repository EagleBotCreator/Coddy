"""Generate the Android color adapter and preview CSS from one token source."""
import json
import sys
from pathlib import Path
root=Path(__file__).resolve().parents[1]
tokens=json.loads((root/"android/design/tokens.json").read_text())
colors="\n".join(f'    val {key[0].upper()+key[1:]} = Color(0xFF{value[1:]})' for key,value in tokens.items())
kotlin=f'// Generated by scripts/generate_design_tokens.py. Do not edit.\npackage dev.coddy.android.ui\nimport androidx.compose.ui.graphics.Color\nobject CoddyColors {{\n{colors}\n}}\n'
css="/* Generated from android/design/tokens.json */\n:root {\n"+"".join(f"  --{key}: {value};\n" for key,value in tokens.items())+"}\n"
xml="<resources>\n"+"".join(f'    <color name="coddy_{key}">{value}</color>\n' for key,value in tokens.items())+"</resources>\n"
outputs={root/"android/app/src/main/res/values/colors.xml":xml,root/"android/app/src/main/java/dev/coddy/android/ui/Colors.kt":kotlin, root/"android/preview/tokens.css":css}
for path,value in outputs.items():
    if "--check" in sys.argv:
        if not path.exists() or path.read_text()!=value:
            raise SystemExit(f"Token drift: {path.relative_to(root)}")
    else:
        path.parent.mkdir(parents=True,exist_ok=True)
        path.write_text(value)
print("Design tokens match." if "--check" in sys.argv else "Design tokens generated.")
